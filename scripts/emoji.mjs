// The emoji module's data, made from emojibase-data (MIT; its names and
// keywords are the Unicode CLDR's annotations): the emoji of each group in
// Unicode's order, each its character, name and keywords; skin tones, the
// regional indicators and emoji newer than the systems' fonts draw left out.
// Written beside the toolbar's bundle (silverware-toolbar-emoji.js, one of its
// library page's `files:`), which imports it the first time the picker opens;
// the playground serves it too.
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const version = JSON.parse(readFileSync(require.resolve("emojibase-data/package.json"), "utf8")).version;
const data = JSON.parse(readFileSync(require.resolve("emojibase-data/en/data.json"), "utf8"));
const messages = JSON.parse(readFileSync(require.resolve("emojibase-data/en/messages.json"), "utf8"));

// Skin tones and hair styles (the component group): parts of other emoji, not emoji to pick
const COMPONENT = 2;
// Each group's emoji in the picker's filters, by emojibase's key: what the group is most plainly
// (a person, not a waving hand; a plane for travel, not the globe; the symbols' own sign)
const GROUP_ICONS = {
  "smileys-emotion": "😀",
  "people-body": "🧑",
  "animals-nature": "🐻",
  "food-drink": "🍔",
  "travel-places": "✈️",
  activities: "⚽",
  objects: "💡",
  symbols: "🔣",
  flags: "🚩",
};

// The newest Emoji version kept: those after it a system's font may not draw yet (an empty box: Emoji 18's
// cracking face in Chrome on Windows, 2026-10-27); raised as the fonts catch up
const MAX_VERSION = 15.1;

/** The module's text: `export default { groups: [{ name, icon, items: [[emoji, name, keywords]] }] }` */
export function emojiModuleText() {
  const groups = messages.groups
    .filter((group) => group.order !== COMPONENT)
    .sort((a, b) => a.order - b.order)
    .map((group) => ({
      name: group.message.replace(/^./, (c) => c.toUpperCase()),
      icon: GROUP_ICONS[group.key],
      items: data
        .filter((emoji) => emoji.group === group.order && emoji.version <= MAX_VERSION)
        .sort((a, b) => a.order - b.order)
        .map((emoji) => [emoji.emoji, emoji.label, (emoji.tags ?? []).join(" ")]),
    }));
  // An icon that is not its group's own (renamed or dropped in a new release of the data) fails the build
  for (const group of groups) if (!group.items.some((item) => item[0] === group.icon)) throw new Error(`emoji: ${group.name} has no icon among its emoji`);
  return `// Generated by scripts/emoji.mjs from emojibase-data ${version} (MIT; names and keywords from Unicode CLDR)\nexport default ${JSON.stringify({ groups })};\n`;
}
