// The emoji module's data, made from emojibase-data (MIT; its names and
// keywords are the Unicode CLDR's annotations): the emoji of each group in
// Unicode's order, each its character, name and keywords; skin tones, the
// regional indicators and emoji newer than the systems' fonts draw left out.
// Silverware Icons' set `emoji` (`emojiSet`, docs/silverware-icons.md), its
// picking data written beside its bundle (silverware-icons-emoji-search.js) by
// the build, which the picker loads as its tab first opens.
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const version = JSON.parse(readFileSync(require.resolve("emojibase-data/package.json"), "utf8")).version;
const data = JSON.parse(readFileSync(require.resolve("emojibase-data/en/data.json"), "utf8"));
const messages = JSON.parse(readFileSync(require.resolve("emojibase-data/en/messages.json"), "utf8"));

// Skin tones and hair styles (the component group): parts of other emoji, not emoji to pick
const COMPONENT = 2;
// Each group's emoji in the picker's filters, by emojibase's key: what the group is most plainly
// (a person, not a waving hand; a plane for travel, not the globe; the symbols' own sign)
const GROUP_ICONS = {
  "smileys-emotion": "😀",
  "people-body": "🧑",
  "animals-nature": "🐻",
  "food-drink": "🍔",
  "travel-places": "✈️",
  activities: "⚽",
  objects: "💡",
  symbols: "🔣",
  flags: "🚩",
};

// The newest Emoji version kept: those after it a system's font may not draw yet (an empty box: Emoji 18's
// cracking face in Chrome on Windows, 2026-10-27); raised as the fonts catch up
const MAX_VERSION = 15.1;

/**
 * The emoji as a set of Silverware Icons (scripts/icons/index.mjs): its picking data only, as a character needs no
 * drawing data; each icon its character (its value as written), name, keywords and its group
 */
export function emojiSet() {
  const groups = messages.groups.filter((group) => group.order !== COMPONENT).sort((a, b) => a.order - b.order);
  const icons = groups.flatMap((group) =>
    data
      .filter((emoji) => emoji.group === group.order && emoji.version <= MAX_VERSION)
      .sort((a, b) => a.order - b.order)
      .map((emoji) => [emoji.emoji, emoji.label, (emoji.tags ?? []).join(" "), [group.key]]),
  );
  const search = {
    groups: groups.map((group) => ({ id: group.key, label: group.message.replace(/^./, (c) => c.toUpperCase()), icon: GROUP_ICONS[group.key] })),
    icons,
  };
  for (const group of search.groups) if (!icons.some((icon) => icon[0] === group.icon && icon[3].includes(group.id))) throw new Error(`emoji: ${group.label} has no icon among its emoji`);
  return {
    name: "emoji",
    label: "Emoji",
    kind: "text",
    license: "emojibase-data (MIT); names and keywords from Unicode CLDR",
    search: `// Generated by scripts/icons/emoji.mjs from emojibase-data ${version} (MIT; names and keywords from Unicode CLDR)\nexport default ${JSON.stringify(search)};\n`,
  };
}
