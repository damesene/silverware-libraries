// The built-in sets of Silverware Icons (docs/silverware-icons.md, *The sets*), in the order its picker's tabs show
// them: each a script making its data. Adding a set is its script and a line here; nothing in silverware-icons/src
// names one. The build writes each set's files beside the bundle and the manifest into src/ (manifestText), and
// check-build compares them.
import { emojiSet } from "./emoji.mjs";
import { lucideSet } from "./lucide.mjs";

const SETS = [lucideSet, emojiSet];

/** Each set made: its name, label, kind, license and its files' texts (`draw` an SVG set's alone, `search` every set's) */
export function iconSets() {
  return SETS.map((make) => make());
}

/** A set's files beside the bundle, by its name: what drawing loads, what picking loads */
export const drawFile = (name) => `silverware-icons-${name}.js`;
export const searchFile = (name) => `silverware-icons-${name}-search.js`;

/** Every file the sets write, by its path in the repository */
export function iconFiles() {
  const sets = iconSets();
  const files = sets.flatMap((set) => [
    ...(set.draw ? [{ path: `silverware-icons/${drawFile(set.name)}`, text: set.draw }] : []),
    { path: `silverware-icons/${searchFile(set.name)}`, text: set.search },
  ]);
  return [...files, { path: "silverware-icons/src/manifest.ts", text: manifestText(sets) }];
}

/** The manifest: what the plugin knows of the built-in sets before any of their files is loaded */
function manifestText(sets) {
  const entries = sets.map((set) => ({
    name: set.name,
    label: set.label,
    kind: set.kind,
    license: set.license,
    ...(set.draw ? { draw: drawFile(set.name) } : {}),
    search: searchFile(set.name),
  }));
  return `// Generated by scripts/icons/index.mjs (npm run build): the built-in sets, their files beside the bundle\nimport type { SetEntry } from "./set.ts";\n\nexport const BUILT_IN_SETS: readonly SetEntry[] = ${JSON.stringify(entries, null, 2)};\n`;
}
