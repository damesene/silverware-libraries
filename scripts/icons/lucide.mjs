// Lucide as a set of Silverware Icons (scripts/icons/index.mjs), made from lucide-static (ISC) as installed and
// lucide-meta.json (its categories and aliases, read from its repository by lucide-meta.mjs): the drawing data
// (each icon's nodes, a path's as its `d` alone; the aliases) and the picking data (each icon's label, keywords and
// categories; the categories).
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);

export function lucideSet() {
  const version = JSON.parse(readFileSync(require.resolve("lucide-static/package.json"), "utf8")).version;
  const nodes = JSON.parse(readFileSync(require.resolve("lucide-static/icon-nodes.json"), "utf8"));
  const tags = JSON.parse(readFileSync(require.resolve("lucide-static/tags.json"), "utf8"));
  const license = readFileSync(require.resolve("lucide-static/LICENSE"), "utf8").trim();
  const meta = JSON.parse(readFileSync(new URL("./lucide-meta.json", import.meta.url), "utf8"));
  // Made from another version's repository: its categories may not be this one's icons
  if (meta.version !== version) throw new Error(`lucide: lucide-meta.json is of ${meta.version}, lucide-static ${version}: run node scripts/icons/lucide-meta.mjs`);
  const names = Object.keys(nodes).sort();
  for (const name of names) if (!meta.icons[name]) throw new Error(`lucide: ${name} is not in lucide-meta.json`);
  for (const name of Object.keys(meta.icons)) if (!nodes[name]) throw new Error(`lucide: lucide-meta.json has ${name}, which lucide-static has not`);
  const known = new Set(meta.categories.map((category) => category.id));
  for (const name of names) for (const id of meta.icons[name].categories) if (!known.has(id)) throw new Error(`lucide: ${name}'s category ${id} is no category`);
  const categories = meta.categories.filter((category) => names.some((name) => meta.icons[name].categories.includes(category.id)));
  for (const category of categories) if (!nodes[category.icon]) throw new Error(`lucide: the category ${category.id}'s icon ${category.icon} is no icon`);

  const aliases = {};
  for (const name of names) for (const alias of meta.icons[name].aliases) if (!nodes[alias] && !aliases[alias]) aliases[alias] = name;
  // (A path of its `d` alone is its text, the most of them: else [tag, attrs])
  const compact = (node) => (node[0] === "path" && Object.keys(node[1]).length === 1 ? node[1].d : node);
  const draw = { icons: Object.fromEntries(names.map((name) => [name, nodes[name].map(compact)])), aliases };
  const search = {
    groups: categories.map((category) => ({ id: category.id, label: category.title, icon: `lucide:${category.icon}` })),
    icons: names.map((name) => [name, labelOf(name), (tags[name] ?? []).join(" "), meta.icons[name].categories]),
  };
  const head = `// Generated by scripts/icons/lucide.mjs from lucide-static ${version}\n/*\n${license}\n*/\n`;
  return {
    name: "lucide",
    label: "Icons",
    kind: "svg",
    license: `Lucide ${version} (ISC)`,
    draw: `${head}export default ${JSON.stringify(draw)};\n`,
    search: `${head}export default ${JSON.stringify(search)};\n`,
  };
}

/** An icon's name as people read it: `arrow-big-down` Arrow big down, `badge-4k` Badge 4k */
function labelOf(name) {
  const words = name.split("-").join(" ");
  return words.charAt(0).toUpperCase() + words.slice(1);
}
